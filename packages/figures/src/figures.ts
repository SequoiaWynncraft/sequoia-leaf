/**
 * Every figure on the stump, typed out as rows of letters (the letters are colours in `pal.ts`).
 * Each has a picture for standing and, for the ones a member can own and the bosses, one for
 * using its ability. `alt` is a second standing picture for things that flap or wobble; without
 * one a figure breathes by sinking a pixel at its `breath` row.
 *
 * All of them face right. A dark edge is added when they are baked (`sprites.ts`).
 *
 * A figure a member can own is up to 22 wide and 26 tall, in the brighter letters of its kin
 * (`pal.ts`). Its pictures are all typed to one width, so that a pose stays over the same feet,
 * and its standing picture has no empty row above it.
 */
import type { UnitKind } from "@sequoia-leaf/raid/content/figures.ts";

export interface FigureArt {
  readonly rows: readonly string[];
  readonly cast?: readonly string[];
  readonly alt?: readonly string[];
  /** The row that folds when it breathes in, counted from the top. */
  readonly breath?: number;
  /** Hovers: its shadow is small and it bobs rather than breathes. */
  readonly flies?: true;
  /** Has something written on it, so it is never mirrored to face the other way. */
  readonly sym?: true;
  /** The row its head starts at, for a small picture of it, where that is not the top. */
  readonly head?: number;
}

