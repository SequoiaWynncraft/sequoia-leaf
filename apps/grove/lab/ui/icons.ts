const cache = new Map<string, string>()
export function icon(name: string, scale = 2) {
  const face = name.startsWith('face'),
    size = face ? 8 : 16
  if (!cache.has(name)) {
    const [colors, rows] = patterns[name] || patterns.star
    const palette = colors.split(' '),
      lines = rows.split('/'),
      canvas = document.createElement('canvas')
    canvas.width = canvas.height = size
    const c = canvas.getContext('2d')!,
      top = Math.floor((size - lines.length) / 2),
      left = Math.max(
        0,
        Math.floor((size - Math.max(...lines.map((l) => l.length))) / 2),
      )
    lines.forEach((row, y) =>
      [...row].forEach((p, x) => {
        if (p !== '.') {
          c.fillStyle = '#' + palette[Number(p) - 1]
          c.fillRect(left + x, top + y, 1, 1)
        }
      }),
    )
    cache.set(name, canvas.toDataURL())
  }
  return (
    '<img class="pixel" alt="" width="' +
    size * scale +
    '" height="' +
    size * scale +
    '" src="' +
    cache.get(name) +
    '">'
  )
}
