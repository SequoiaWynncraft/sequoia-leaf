const bodies = new Map<string, Body>();
/** The walking, sitting figure for a guild-mate, by their handle. */
export function bodyOf(name: string): Body {
  let b = bodies.get(name);
  if (!b) {
    b = bake(paintSkin(LOOKS[name] ?? ANYBODY));
    bodies.set(name, b);
  }
  return b;
}
